import { useState } from "react";
import { Download, FileText, RefreshCw, Sparkles } from "lucide-react";
import { api, useApi } from "@/lib/api";
import type { Job, ReportFile } from "@/lib/types";
import { Badge, Button, Empty, Field, PageHeader, Panel, Stat } from "@/components/ui";
import { JobOutput } from "@/components/JobDrawer";
import { formatBytes, formatDateTime } from "@/lib/format";

export default function Reports() {
  const [jobId, setJobId] = useState<string | null>(null);
  const [form, setForm] = useState({
    title: "Pegasus Security Assessment",
    tester: "operator",
    target: "",
    notes: "Authorized assessment. Findings generated by Pegasus Phantom Menace.",
  });

  const files = useApi<{ reports: ReportFile[]; directory: string }>("/reports", { interval: 20000 });

  const generate = async () => {
    const data = await api.post<{ job: Job }>("/reports/generate", form);
    setJobId(data.job.id);
  };

  const reports = files.data?.reports ?? [];
  const html = reports.filter((r) => r.format === "HTML").length;

  return (
    <div className="page">
      <PageHeader
        title="Reports"
        subtitle="HTML/JSON pentest reports with findings and evidence"
        actions={<Button size="sm" onClick={files.refresh}><RefreshCw size={12} /> Refresh</Button>}
      />

      <div className="stat-grid">
        <Stat value={reports.length} label="Report artifacts" tone="info" />
        <Stat value={html} label="HTML reports" />
        <Stat value={reports.filter((r) => r.format === "JSON").length} label="JSON exports" />
        <Stat value={files.data?.directory ? "OK" : "—"} label="Output directory" hint={files.data?.directory ?? "—"} />
      </div>

      <Panel title="Generate report">
        <div className="form-row">
          <Field label="Title">
            <input className="input" value={form.title} onChange={(e) => setForm({ ...form, title: e.target.value })} />
          </Field>
          <Field label="Tester">
            <input className="input" value={form.tester} onChange={(e) => setForm({ ...form, tester: e.target.value })} />
          </Field>
          <Field label="Target">
            <input className="input" value={form.target} onChange={(e) => setForm({ ...form, target: e.target.value })} placeholder="device serial or host" />
          </Field>
          <Field label="Generate">
            <button className="btn btn-primary" onClick={() => void generate()}>
              <Sparkles size={13} /> Build report
            </button>
          </Field>
        </div>
        <Field label="Notes / scope">
          <textarea className="textarea" value={form.notes} onChange={(e) => setForm({ ...form, notes: e.target.value })} />
        </Field>
      </Panel>

      <Panel title="Report archive" tight>
        {reports.length === 0 ? (
          <Empty icon={<FileText size={16} />} title="No reports generated" detail="Build one to populate the archive." action={<Button size="sm" variant="primary" onClick={() => void generate()}>Generate</Button>} />
        ) : (
          <div className="table-wrap">
            <table className="tbl">
              <thead><tr><th>Report</th><th>Format</th><th>Size</th><th>Created</th><th /></tr></thead>
              <tbody>
                {reports.map((report) => (
                  <tr key={report.name}>
                    <td className="td-strong td-truncate">{report.name}</td>
                    <td><Badge tone={report.format === "HTML" ? "primary" : "dim"}>{report.format}</Badge></td>
                    <td className="mono tiny">{formatBytes(report.sizeBytes)}</td>
                    <td className="tiny mute">{formatDateTime(report.createdAt)}</td>
                    <td>
                      <a className="btn btn-xs" href={`/api/reports/${encodeURIComponent(report.name)}`} target="_blank" rel="noreferrer">
                        <Download size={11} /> open
                      </a>
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        )}
      </Panel>

      {jobId && (
        <Panel title="Report build">
          <JobOutput jobId={jobId} title="report generator" height={280} onDone={() => files.refresh()} />
        </Panel>
      )}
    </div>
  );
}
